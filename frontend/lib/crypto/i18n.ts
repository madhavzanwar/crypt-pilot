/** Translate a crypto-component key: the Hindi / Marathi rows above first, then FinPilot's table, then the English default. */
export function ct(lang: Lang, key: string, fallback?: string): string {
  const row = S[key];
  const hit = row && (lang === "hi" ? row[0] : lang === "mr" ? row[1] : "");
  if (hit) return hit;
  return translate(lang, key, fallback);
}

/** Drop-in for `useT()` in the crypto components. */
export function useCryptoT() {
  const lang = useLang();
  return { lang, t: (key: string, fallback?: string) => ct(lang, key, fallback) };
}

